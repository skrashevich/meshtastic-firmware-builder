package jobs

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

func prepareBuildConfigOverrides(repoPath string, baseEnvName string, jobID string, firmwareVersion string, options BuildOptions) (string, string, error) {
	if options.IsEmpty() {
		return "", baseEnvName, nil
	}
	if err := ValidateDevice(baseEnvName); err != nil {
		return "", "", fmt.Errorf("invalid target environment %q: %w", baseEnvName, err)
	}

	overrideEnvName := buildOverrideEnvName(jobID)
	if err := ValidateDevice(overrideEnvName); err != nil {
		return "", "", fmt.Errorf("invalid override environment name %q: %w", overrideEnvName, err)
	}

	configAbsolutePath := filepath.Join(repoPath, "platformio.ini")
	options = cacheBustBranchArchiveLibDeps(options, jobID)
	options, err := applyReplacementLibDeps(repoPath, baseEnvName, options)
	if err != nil {
		return "", "", err
	}

	content := renderBuildOverrideConfig(baseEnvName, overrideEnvName, firmwareVersion, options)
	file, err := os.OpenFile(configAbsolutePath, os.O_APPEND|os.O_WRONLY, 0)
	if err != nil {
		return "", "", fmt.Errorf("open platformio.ini for build overrides: %w", err)
	}
	defer file.Close()

	if _, err := file.WriteString(content); err != nil {
		return "", "", fmt.Errorf("append build override config: %w", err)
	}

	return "", overrideEnvName, nil
}

func buildOverrideEnvName(jobID string) string {
	trimmed := strings.TrimSpace(jobID)
	if trimmed == "" {
		return "mfb-custom"
	}

	builder := strings.Builder{}
	builder.Grow(len(trimmed) + 11)
	builder.WriteString("mfb-custom-")
	for _, char := range trimmed {
		switch {
		case char >= 'a' && char <= 'z':
			builder.WriteRune(char)
		case char >= 'A' && char <= 'Z':
			builder.WriteRune(char + 32)
		case char >= '0' && char <= '9':
			builder.WriteRune(char)
		default:
			builder.WriteRune('-')
		}
	}
	return builder.String()
}

func renderBuildOverrideConfig(baseEnvName string, overrideEnvName string, firmwareVersion string, options BuildOptions) string {
	builder := strings.Builder{}
	builder.WriteString("\n; generated by meshtastic-firmware-builder\n")
	builder.WriteString("[env:")
	builder.WriteString(overrideEnvName)
	builder.WriteString("]\n")
	builder.WriteString("extends = env:")
	builder.WriteString(baseEnvName)
	builder.WriteString("\n")

	buildFlags := appendMeshtasticBuildFlagFallbacks(options.BuildFlags, firmwareVersion)
	appendOverrideOption(&builder, "build_flags", baseEnvName, buildFlags)
	appendOverrideOption(&builder, "lib_deps", baseEnvName, options.LibDeps)

	return builder.String()
}

func appendMeshtasticBuildFlagFallbacks(values []string, firmwareVersion string) []string {
	version := strings.TrimSpace(firmwareVersion)
	if version == "" || hasBuildFlagDefine(values, "APP_VERSION") {
		return values
	}

	flags := append([]string(nil), values...)
	flags = append(flags, "-DAPP_VERSION=\\\""+escapeBuildFlagValue(version)+"\\\"")

	shortVersion := meshtasticShortVersion(version)
	if shortVersion != "" && shortVersion != version && !hasBuildFlagDefine(values, "APP_VERSION_SHORT") {
		flags = append(flags, "-DAPP_VERSION_SHORT=\\\""+escapeBuildFlagValue(shortVersion)+"\\\"")
	}

	return flags
}

func hasBuildFlagDefine(values []string, name string) bool {
	prefix := "-D" + name
	for _, value := range values {
		trimmed := strings.TrimSpace(value)
		if trimmed == prefix || strings.HasPrefix(trimmed, prefix+"=") {
			return true
		}
	}
	return false
}

func meshtasticShortVersion(version string) string {
	parts := strings.Split(version, ".")
	if len(parts) < 3 {
		return ""
	}
	return strings.Join(parts[:3], ".")
}

func escapeBuildFlagValue(value string) string {
	replacer := strings.NewReplacer("\\", "\\\\", "\"", "\\\"")
	return replacer.Replace(value)
}

func cacheBustBranchArchiveLibDeps(options BuildOptions, jobID string) BuildOptions {
	if len(options.LibDeps) == 0 {
		return options
	}

	libDeps := make([]string, 0, len(options.LibDeps))
	for _, value := range options.LibDeps {
		libDeps = append(libDeps, cacheBustBranchArchiveURL(value, jobID))
	}
	options.LibDeps = libDeps
	return options
}

func cacheBustBranchArchiveURL(value string, jobID string) string {
	trimmed := strings.TrimSpace(value)
	if trimmed == "" || strings.Contains(trimmed, "?") || !strings.Contains(trimmed, "/archive/refs/heads/") ||
		!strings.HasSuffix(strings.ToLower(trimmed), ".zip") {
		return value
	}

	cacheKey := buildOverrideEnvName(jobID)
	if cacheKey == "mfb-custom" {
		return value
	}
	return value + "?mfb=" + cacheKey
}

func applyReplacementLibDeps(repoPath string, baseEnvName string, options BuildOptions) (BuildOptions, error) {
	if len(options.LibDeps) == 0 {
		return options, nil
	}

	configPaths, err := platformIOConfigPaths(repoPath)
	if err != nil {
		return options, err
	}

	remaining := make([]string, 0, len(options.LibDeps))
	for _, value := range options.LibDeps {
		if !isDeviceUILibDep(value) {
			remaining = append(remaining, value)
			continue
		}

		replaced, err := replaceDeviceUILibDep(configPaths, baseEnvName, value)
		if err != nil {
			return options, err
		}
		if !replaced {
			remaining = append(remaining, value)
		}
	}

	options.LibDeps = remaining
	return options, nil
}

func platformIOConfigPaths(repoPath string) ([]string, error) {
	var paths []string
	if err := filepath.WalkDir(repoPath, func(path string, entry os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() {
			switch entry.Name() {
			case ".git", ".pio", "build", "dist", "node_modules":
				return filepath.SkipDir
			}
			return nil
		}
		if entry.Name() == "platformio.ini" {
			paths = append(paths, path)
		}
		return nil
	}); err != nil {
		return nil, fmt.Errorf("find platformio.ini files for replacement lib_deps: %w", err)
	}
	return paths, nil
}

func replaceDeviceUILibDep(configPaths []string, baseEnvName string, value string) (bool, error) {
	type candidate struct {
		path  string
		lines []string
		index int
	}

	var fallback *candidate
	for _, path := range configPaths {
		content, err := os.ReadFile(path)
		if err != nil {
			return false, fmt.Errorf("read platformio.ini for replacement lib_deps: %w", err)
		}

		lines := strings.Split(string(content), "\n")
		deviceUISections := findDeviceUILibDepSections(lines)
		if index := findDeviceUILibDepLineInSection(lines, "env:"+baseEnvName, deviceUISections); index >= 0 {
			return writeReplacementLibDep(path, lines, index, value)
		}

		if fallback == nil {
			if index := findDeviceUILibDepLine(lines, deviceUISections); index >= 0 {
				fallback = &candidate{path: path, lines: lines, index: index}
			}
		}
	}

	if fallback == nil {
		return false, nil
	}
	return writeReplacementLibDep(fallback.path, fallback.lines, fallback.index, value)
}

func writeReplacementLibDep(configPath string, lines []string, index int, value string) (bool, error) {
	indent := lines[index][:len(lines[index])-len(strings.TrimLeft(lines[index], " \t"))]
	lines[index] = indent + value
	if err := os.WriteFile(configPath, []byte(strings.Join(lines, "\n")), 0o644); err != nil {
		return false, fmt.Errorf("write platformio.ini replacement lib_deps: %w", err)
	}
	return true, nil
}

func findDeviceUILibDepLine(lines []string, deviceUISections map[string]struct{}) int {
	for index, line := range lines {
		trimmed := strings.TrimSpace(line)
		if trimmed == "" || strings.HasPrefix(trimmed, ";") || strings.HasPrefix(trimmed, "#") {
			continue
		}
		if isDeviceUILibDep(trimmed) || strings.EqualFold(trimmed, "symlink://../device-ui/") || isLibDepsReferenceToSection(trimmed, deviceUISections) {
			return index
		}
	}
	return -1
}

func findDeviceUILibDepLineInSection(lines []string, sectionName string, deviceUISections map[string]struct{}) int {
	inSection := false
	currentOption := ""
	for index, line := range lines {
		trimmed := strings.TrimSpace(line)
		if trimmed == "" {
			currentOption = ""
			continue
		}
		if strings.HasPrefix(trimmed, ";") || strings.HasPrefix(trimmed, "#") {
			continue
		}

		sectionMatch := sectionPattern.FindStringSubmatch(trimmed)
		if len(sectionMatch) == 2 {
			inSection = strings.EqualFold(strings.TrimSpace(sectionMatch[1]), sectionName)
			currentOption = ""
			continue
		}
		if !inSection {
			currentOption = ""
			continue
		}

		isContinuation := (strings.HasPrefix(line, " ") || strings.HasPrefix(line, "\t")) && currentOption != ""
		if isContinuation {
			value := parseOptionValue(trimmed)
			if currentOption == "lib_deps" && isReplacementLibDepLine(value, deviceUISections) {
				return index
			}
			continue
		}

		key, value, ok := splitIniOption(trimmed)
		if !ok {
			currentOption = ""
			continue
		}
		if strings.EqualFold(key, "lib_deps") {
			currentOption = "lib_deps"
			if isReplacementLibDepLine(parseOptionValue(value), deviceUISections) {
				return index
			}
			continue
		}
		currentOption = ""
	}
	return -1
}

func findDeviceUILibDepSections(lines []string) map[string]struct{} {
	sections := make(map[string]struct{})
	currentSection := ""
	currentOption := ""
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		if trimmed == "" {
			currentOption = ""
			continue
		}
		if strings.HasPrefix(trimmed, ";") || strings.HasPrefix(trimmed, "#") {
			continue
		}

		sectionMatch := sectionPattern.FindStringSubmatch(trimmed)
		if len(sectionMatch) == 2 {
			currentSection = strings.TrimSpace(sectionMatch[1])
			currentOption = ""
			continue
		}
		if currentSection == "" {
			currentOption = ""
			continue
		}

		isContinuation := (strings.HasPrefix(line, " ") || strings.HasPrefix(line, "\t")) && currentOption != ""
		if isContinuation {
			value := parseOptionValue(trimmed)
			if currentOption == "lib_deps" && isReplacementLibDep(value) {
				sections[currentSection] = struct{}{}
			}
			continue
		}

		key, value, ok := splitIniOption(trimmed)
		if !ok {
			currentOption = ""
			continue
		}
		if strings.EqualFold(key, "lib_deps") {
			currentOption = "lib_deps"
			if isReplacementLibDep(parseOptionValue(value)) {
				sections[currentSection] = struct{}{}
			}
			continue
		}
		currentOption = ""
	}
	return sections
}

func isLibDepsReferenceToSection(value string, sections map[string]struct{}) bool {
	trimmed := strings.TrimSpace(value)
	if !strings.HasPrefix(trimmed, "${") || !strings.HasSuffix(trimmed, "}") {
		return false
	}

	reference := strings.TrimSuffix(strings.TrimPrefix(trimmed, "${"), "}")
	sectionName, optionName, ok := strings.Cut(reference, ".")
	if !ok || !strings.EqualFold(strings.TrimSpace(optionName), "lib_deps") {
		return false
	}
	_, exists := sections[strings.TrimSpace(sectionName)]
	return exists
}

func isReplacementLibDep(value string) bool {
	return isDeviceUILibDep(value) || strings.EqualFold(strings.TrimSpace(value), "symlink://../device-ui/")
}

func isReplacementLibDepLine(value string, deviceUISections map[string]struct{}) bool {
	return isReplacementLibDep(value) || isLibDepsReferenceToSection(value, deviceUISections)
}

func isDeviceUILibDep(value string) bool {
	normalized := strings.ToLower(strings.TrimSpace(value))
	return strings.Contains(normalized, "github.com/meshtastic/device-ui") ||
		strings.Contains(normalized, "github.com/skrashevich/device-ui")
}

func appendOverrideOption(builder *strings.Builder, optionName string, baseEnvName string, values []string) {
	if len(values) == 0 {
		return
	}

	builder.WriteString(optionName)
	builder.WriteString(" =\n")
	builder.WriteString("  ${env:")
	builder.WriteString(baseEnvName)
	builder.WriteString(".")
	builder.WriteString(optionName)
	builder.WriteString("}\n")
	for _, value := range values {
		builder.WriteString("  ")
		builder.WriteString(value)
		builder.WriteString("\n")
	}
}
